export function findDirection(slug) {
  return directions.find(item => item.slug === slug);
}

export function findSection(directionSlug, slug) {
  return sections.find(item => item.directionSlug === directionSlug && item.slug === slug);
}

export function findCategory(directionSlug, sectionSlug, slug) {
  return categories.find(item => item.directionSlug === directionSlug && item.sectionSlug === sectionSlug && item.slug === slug);
}

export function findSituation(directionSlug, sectionSlug, categorySlug, slug) {
  return situations.find(item => item.directionSlug === directionSlug && item.sectionSlug === sectionSlug && item.categorySlug === categorySlug && item.slug === slug);
}
